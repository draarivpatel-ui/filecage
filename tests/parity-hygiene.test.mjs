function walk(directory) {
  const output = [];
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (entry.name === '.git' || entry.name === 'node_modules') continue;
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) output.push(...walk(full));
    else if (entry.isFile()) output.push(full);
  }
  return output;
}

const textExtensions = new Set(['.mjs', '.cjs', '.js', '.ts', '.json', '.md', '.yml', '.yaml', '.txt']);
const repositoryFiles = walk(root).filter((file) => {
  if (file.endsWith('.gitattributes') || file.endsWith('.gitignore')) return true;
  return textExtensions.has(path.extname(file));
});

test('repository scan covers a substantial number of text files', () => {
  assert.equal(repositoryFiles.length >= 25, true, String(repositoryFiles.length));
});

for (const file of repositoryFiles) {
  test('text file uses LF line endings: ' + path.relative(root, file), () => {
    const bytes = readFileSync(file);
    assert.equal(bytes.includes(13), false);
  });
}

const dashPattern = new RegExp('[\\u2013\\u2014]');
for (const file of repositoryFiles) {
  test('text file has no em or en dashes: ' + path.relative(root, file), () => {
    assert.equal(dashPattern.test(readFileSync(file, 'utf8')), false, file);
  });
}

for (const file of repositoryFiles) {
  test('text file has no machine-local absolute path: ' + path.relative(root, file), () => {
    const text = readFileSync(file, 'utf8');
    assert.equal(text.includes('/Us' + 'ers/'), false, file);
    assert.equal(/[A-Za-z]:\\\\Users\\\\/.test(text), false, file);
  });
}

const emailPattern = /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/;
for (const file of repositoryFiles) {
  test('text file has no unexpected email address: ' + path.relative(root, file), () => {
    const text = readFileSync(file, 'utf8');
    const matches = text.match(new RegExp(emailPattern, 'g')) || [];
    assert.deepEqual(matches.filter((item) => !item.endsWith('users.noreply.github.com')), []);
  });
}

