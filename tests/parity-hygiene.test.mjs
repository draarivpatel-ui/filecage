test('FileCageError behaves identically in both module formats', () => {
  for (const mod of [esm, cjs]) {
    const error = new mod.FileCageError('FILECAGE_TEST', 'reason', { position: 4 });
    assert.equal(error.name, 'FileCageError');
    assert.equal(error.code, 'FILECAGE_TEST');
    assert.equal(error.reason, 'reason');
    assert.equal(error.position, 4);
    assert.equal(error.toJSON().code, 'FILECAGE_TEST');
  }
});

const parityCases = [
  ['sniff PNG', (mod) => mod.sniffFileType(png()).mime, 'image/png'],
  ['sniff JPEG', (mod) => mod.sniffFileType(jpeg()).format, 'jpeg'],
  ['dimensions', (mod) => mod.inspectImageDimensions(png(2, 3)).pixels, 6],
  ['clean validation', (mod) => mod.validateUpload({ bytes: png(), filename: 'x.png', contentType: 'image/png' }).allowed, true],
  ['MIME mismatch', (mod) => mod.validateUpload({ bytes: png(), filename: 'x.png', contentType: 'image/jpeg' }).code, 'FILECAGE_MIME_MISMATCH'],
  ['extension mismatch', (mod) => mod.validateUpload({ bytes: png(), filename: 'x.jpg', contentType: 'image/png' }).findings.some((item) => item.code === 'FILECAGE_EXTENSION_MISMATCH'), true],
  ['executable rejection', (mod) => mod.validateUpload({ bytes: new Uint8Array([0x4d, 0x5a]), filename: 'x.png' }).code, 'FILECAGE_EXECUTABLE_TYPE'],
  ['filename sanitization', (mod) => mod.sanitizeFilename('../x.png').filename, 'x.png'],
  ['reserved filename', (mod) => mod.sanitizeFilename('CON.txt').findings[0].code, 'FILECAGE_FILENAME_RESERVED_DEVICE'],
  ['safe assertion', (mod) => mod.assertSafeFilename('x.png').filename, 'x.png'],
  ['buffer inspection', (mod) => mod.inspectFileBuffer(png()).detectedFormat, 'png'],
  ['guard creation', (mod) => mod.createUploadGuard('images-safe').policy.preset, 'images-safe'],
  ['cage alias', (mod) => mod.createFileCage('images-safe').validateUpload({ bytes: png(), filename: 'x.png', contentType: 'image/png' }).allowed, true],
  ['SVG detection', (mod) => mod.sniffFileType(svg()).format, 'svg'],
  ['text detection', (mod) => mod.sniffFileType(ascii('hello\nworld')).format, 'text']
];
for (const [label, run, expected] of parityCases) {
  test('ESM behavior parity: ' + label, () => {
    assert.equal(run(esm), expected);
  });
  test('CommonJS behavior parity: ' + label, () => {
    assert.equal(run(cjs), expected);
  });
}

