/*
 * Generate the CommonJS build from the single ESM source of truth.
 * The transform is explicit, deterministic, and limited to Node built-in
 * imports plus the exported declarations used by this library.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
for (const arg of args) {
  if (arg !== '--check') throw new Error('unknown build-cjs argument: ' + arg);
}
const check = args.includes('--check');
const source = await readFile(path.join(root, 'src', 'index.mjs'), 'utf8');

const EXPORT_NAMES = [
  'FILECAGE_VERSION',
  'FILECAGE_ERROR_CODES',
  'CODE',
  'FILECAGE_PRESETS',
  'FileCageError',
  'sniffFileType',
  'inspectImageDimensions',
  'inspectFileBuffer',
  'validateUpload',
  'validateFilePath',
  'validateWebFile',
  'createUploadGuard',
  'createFileCage',
  'sanitizeFilename',
  'assertSafeFilename'
];

let body = source;
for (const name of EXPORT_NAMES) {
  const pattern = new RegExp('^export (?:const|class|function|async function) ' + name + '\\b', 'm');
  if (!pattern.test(body)) throw new Error('CJS transform could not find export ' + name);
}

body = body.replace(/^import \{([^}]+)\} from '(node:[^']+)';$/gm, (whole, names, specifier) => {
  const destructured = names.replace(/\b([A-Za-z_$][\w$]*)\s+as\s+([A-Za-z_$][\w$]*)\b/g, '$1: $2');
  return 'const {' + destructured + '} = require(\'' + specifier + '\');';
});
if (/^import\s/m.test(body)) throw new Error('CJS transform found an untransformed import');

body = body.replace(/^export const /gm, 'const ');
body = body.replace(/^export class /gm, 'class ');
body = body.replace(/^export function /gm, 'function ');
body = body.replace(/^export async function /gm, 'async function ');
if (/^export\s/m.test(body.replace(/export default filecage;\s*$/, ''))) {
  throw new Error('CJS transform found an untransformed export');
}

const defaultObjectStart = body.indexOf('const filecage = Object.freeze({');
if (defaultObjectStart === -1) throw new Error('CJS transform could not find the default export object');
if (!body.trimEnd().endsWith('export default filecage;')) {
  throw new Error('CJS transform could not find the default export statement');
}
body = body.slice(0, defaultObjectStart).trimEnd();

const output = [
  "'use strict';",
  '',
  '/* Generated by scripts/build-cjs.mjs from src/index.mjs. Do not edit directly. */',
  '',
  body,
  '',
  'module.exports = {',
  ...EXPORT_NAMES.map((name) => '  ' + name + ','),
  '};',
  '',
  'module.exports.default = module.exports;',
  ''
].join('\n');

const outputPath = path.join(root, 'cjs', 'index.cjs');
if (check) {
  const current = await readFile(outputPath).catch(() => null);
  if (current === null) {
    console.error('cjs/index.cjs is missing or unreadable');
    process.exitCode = 1;
  } else if (!current.equals(Buffer.from(output, 'utf8'))) {
    console.error('cjs/index.cjs is stale; run node scripts/build-cjs.mjs');
    process.exitCode = 1;
  } else {
    process.stdout.write('cjs/index.cjs is up to date\n');
  }
} else {
  await mkdir(path.join(root, 'cjs'), { recursive: true });
  await writeFile(outputPath, output, 'utf8');
  process.stdout.write('cjs/index.cjs generated from src/index.mjs\n');
}
